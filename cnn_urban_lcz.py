def train_cnn(train_indices, val_indices, test_indices, seed):
    set_seed(seed)

    train_ds = PatchDataset(feature_stack, lst_array, train_indices, PATCH_SIZE_CNN)
    val_ds = PatchDataset(feature_stack, lst_array, val_indices, PATCH_SIZE_CNN)
    test_ds = PatchDataset(feature_stack, lst_array, test_indices, PATCH_SIZE_CNN)

    train_loader = DataLoader(
        train_ds,
        batch_size=CNN_BATCH_SIZE,
        shuffle=True,
        num_workers=0,
        pin_memory=torch.cuda.is_available()
    )

    val_loader = DataLoader(
        val_ds,
        batch_size=CNN_BATCH_SIZE,
        shuffle=False,
        num_workers=0,
        pin_memory=torch.cuda.is_available()
    )

    test_loader = DataLoader(
        test_ds,
        batch_size=CNN_BATCH_SIZE,
        shuffle=False,
        num_workers=0,
        pin_memory=torch.cuda.is_available()
    )

    model = SimplePatchCNN(in_channels=feature_stack.shape[0]).to(DEVICE)

    print(f"CNN input channels: {feature_stack.shape[0]}")
    print(f"CNN trainable parameters: {count_trainable_parameters(model):,}")

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=CNN_LR,
        weight_decay=CNN_WEIGHT_DECAY
    )

    loss_fn = nn.MSELoss()

    best_state = None
    best_val = float("inf")
    patience_count = 0

    train_losses = []
    val_losses = []

    for epoch in range(CNN_EPOCHS):
        t0 = time.time()

        model.train()
        batch_losses = []

        for xb, yb in train_loader:
            xb = xb.to(DEVICE)
            yb = yb.to(DEVICE)

            optimizer.zero_grad()
            pred = model(xb)
            loss = loss_fn(pred, yb)

            loss.backward()
            optimizer.step()

            batch_losses.append(loss.item())

        model.eval()
        val_batch_losses = []

        with torch.no_grad():
            for xb, yb in val_loader:
                xb = xb.to(DEVICE)
                yb = yb.to(DEVICE)

                pred = model(xb)
                val_loss = loss_fn(pred, yb)

                val_batch_losses.append(val_loss.item())

        train_loss = float(np.mean(batch_losses))
        val_loss = float(np.mean(val_batch_losses))

        train_losses.append(train_loss)
        val_losses.append(val_loss)

        if val_loss < best_val:
            best_val = val_loss
            best_state = {
                k: v.detach().cpu().clone()
                for k, v in model.state_dict().items()
            }
            patience_count = 0
        else:
            patience_count += 1

        if epoch % 10 == 0 or epoch == CNN_EPOCHS - 1:
            print(
                f"Epoch {epoch:03d} | "
                f"train MSE: {train_loss:.4f} | "
                f"val MSE: {val_loss:.4f} | "
                f"time: {time.time() - t0:.2f}s"
            )

        if patience_count >= CNN_PATIENCE:
            print(f"Early stopping at epoch {epoch}")
            break

    if best_state is not None:
        model.load_state_dict(best_state)

    preds = []
    targets = []

    model.eval()

    with torch.no_grad():
        for xb, yb in test_loader:
            xb = xb.to(DEVICE)

            pred = model(xb).cpu().numpy()

            preds.append(pred)
            targets.append(yb.numpy())

    preds = np.concatenate(preds)
    targets = np.concatenate(targets)

    metrics = regression_metrics(targets, preds)

    return model, metrics, preds, targets, train_losses, val_losses


