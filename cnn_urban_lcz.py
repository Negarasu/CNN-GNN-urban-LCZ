def calculate_PLAND(lcz_array, window_size, lcz_classes=range(1, 18)):
    pland = np.zeros(
        (lcz_array.shape[0], lcz_array.shape[1], len(list(lcz_classes))),
        dtype=np.float32
    )

    for i, lcz_class in enumerate(lcz_classes):
        binary_mask = (lcz_array == lcz_class).astype(np.float32)
        pland[:, :, i] = ndimage.uniform_filter(binary_mask, size=window_size)

    return pland


def calculate_SHDI(lcz_array, window_size):
    def shannon_diversity(window):
        valid = window[(window > 0) & (window <= 17)]
        if valid.size == 0:
            return 0.0
        _, counts = np.unique(valid, return_counts=True)
        p = counts / counts.sum()
        return -np.sum(p * np.log(p + 1e-8))

    return ndimage.generic_filter(
        lcz_array,
        shannon_diversity,
        size=window_size
    ).astype(np.float32)


def calculate_PD(lcz_array, window_size):
    def count_patches(window):
        valid = window[(window > 0) & (window <= 17)]
        if valid.size == 0:
            return 0.0
        return len(np.unique(valid)) / (window_size * window_size)

    return ndimage.generic_filter(
        lcz_array,
        count_patches,
        size=window_size
    ).astype(np.float32)


def build_feature_stack(lcz_array, window_size):
    print("Calculating lightweight feature maps without coordinates...")

    H, W = lcz_array.shape

    pland = calculate_PLAND(lcz_array, window_size)
    shdi = calculate_SHDI(lcz_array, window_size)
    pdens = calculate_PD(lcz_array, window_size)

    # Heavy metrics disabled for large CONUS-scale data
    contag = np.zeros((H, W), dtype=np.float32)
    shape_am = np.zeros((H, W), dtype=np.float32)
    teci = np.zeros((H, W), dtype=np.float32)
    ai = np.zeros((H, W), dtype=np.float32)

    feature_maps = [
        contag,
        shdi,
        shape_am,
        teci,
        ai,
        pdens
    ]

    feature_names = [
        "CONTAG_zero",
        "SHDI",
        "SHAPE_AM_zero",
        "TECI_zero",
        "AI_zero",
        "PD"
    ]

    existing_lcz = [int(c) for c in np.unique(lcz_array) if 1 <= c <= 17]

    for cls in existing_lcz:
        fmap = pland[:, :, cls - 1].copy()
        fmap[lcz_array == cls] = 1.0
        feature_maps.append(fmap.astype(np.float32))
        feature_names.append(f"PLAND_LCZ_{cls}")

    stack = np.stack(feature_maps, axis=0).astype(np.float32)
    stack = np.nan_to_num(stack, nan=0.0, posinf=0.0, neginf=0.0)

    print("Feature stack:", stack.shape)
    print("Feature names:", feature_names)

    return stack, feature_names


