def create_random_split(valid_indices, seed, train_ratio=0.6, val_ratio=0.1):
    set_seed(seed)

    n = len(valid_indices)
    perm = torch.randperm(n).cpu().numpy()

    n_train = int(n * train_ratio)
    n_val = int(n * val_ratio)

    train_pos = perm[:n_train]
    val_pos = perm[n_train:n_train + n_val]
    test_pos = perm[n_train + n_val:]

    train_indices = valid_indices[train_pos]
    val_indices = valid_indices[val_pos]
    test_indices = valid_indices[test_pos]

    return train_indices, val_indices, test_indices


