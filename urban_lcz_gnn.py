def calculate_TECI(lcz_array, window_size):
    """Total Edge Contrast Index to measure contrast between adjacent patch types"""
    H, W = lcz_array.shape
    TECI_map = np.zeros((H, W))

    half_window = window_size // 2

    def get_contrast_weight(class1, class2):
        built1 = 1 <= class1 <= 10
        built2 = 1 <= class2 <= 10
        natural1 = 11 <= class1 <= 17
        natural2 = 11 <= class2 <= 17

        if (built1 and built2) or (natural1 and natural2):
            return 0.0
        elif (built1 and natural2) or (natural1 and built2):
            return 1.0
        else:
            return 0.5

    for i in range(half_window, H - half_window):
        for j in range(half_window, W - half_window):
            window = lcz_array[i-half_window:i+half_window+1, j-half_window:j+half_window+1]

            total_contrast = 0
            total_edges = 0

            for x in range(window.shape[0]):
                for y in range(window.shape[1] - 1):
                    contrast = get_contrast_weight(window[x, y], window[x, y + 1])
                    total_contrast += contrast
                    total_edges += 1

            for x in range(window.shape[0] - 1):
                for y in range(window.shape[1]):
                    contrast = get_contrast_weight(window[x, y], window[x + 1, y])
                    total_contrast += contrast
                    total_edges += 1

            if total_edges > 0:
                TECI_map[i, j] = total_contrast / total_edges
            else:
                TECI_map[i, j] = 0

    return TECI_map

def calculate_AI(lcz_array, window_size):
    """
    Aggregation Index to measure degree of aggregation of patches
    """
    H, W = lcz_array.shape
    AI_map = np.zeros((H, W))

    half_window = window_size // 2

    for i in range(half_window, H - half_window):
        for j in range(half_window, W - half_window):
            window = lcz_array[i-half_window:i+half_window+1, j-half_window:j+half_window+1]

            max_possible_edges = 0
            actual_edges = 0

            for x in range(window.shape[0]):
                for y in range(window.shape[1] - 1):
                    max_possible_edges += 1
                    if window[x, y] == window[x, y + 1]:
                        actual_edges += 1

            for x in range(window.shape[0] - 1):
                for y in range(window.shape[1]):
                    max_possible_edges += 1
                    if window[x, y] == window[x + 1, y]:
                        actual_edges += 1

            if max_possible_edges > 0:
                AI_map[i, j] = actual_edges / max_possible_edges
            else:
                AI_map[i, j] = 0

    return AI_map

def calculate_PD(lcz_array, window_size):
    """
    Patch Density to measure number of different patch types per unit area
    """
    def count_patches(window):
        unique_classes = np.unique(window)
        valid_classes = [c for c in unique_classes if 1 <= c <= 17]
        return len(valid_classes)

    PD_map = ndimage.generic_filter(lcz_array, count_patches, size=window_size)
    PD_map = PD_map / (window_size * window_size)
    return PD_map

def calculate_contagion_fast(lcz_array, window_size):
    from itertools import product

    H, W = lcz_array.shape
    contag_map = np.zeros((H, W))
    unique_classes = np.unique(lcz_array)
    m = len(unique_classes)

    if m <= 1:
        return contag_map

    half_window = window_size // 2

    class_pairs = list(product(unique_classes, repeat=2))

    for i in range(half_window, H - half_window):
        for j in range(half_window, W - half_window):
            window = lcz_array[i-half_window:i+half_window+1, j-half_window:j+half_window+1]

            horizontal_diff = window[:, :-1] != window[:, 1:]
            h_same_pairs = np.sum(~horizontal_diff)
            h_total_pairs = horizontal_diff.size

            vertical_diff = window[:-1, :] != window[1:, :]
            v_same_pairs = np.sum(~vertical_diff)
            v_total_pairs = vertical_diff.size

            total_pairs = h_total_pairs + v_total_pairs
            same_pairs = h_same_pairs + v_same_pairs

            if total_pairs == 0:
                contag_map[i, j] = 0
                continue

            p_same = same_pairs / total_pairs
            p_diff = 1 - p_same

            if p_same > 0 and p_diff > 0:
                contag = p_same * np.log(p_same) + p_diff * np.log(p_diff)
                contag = 1 + contag / (2 * np.log(m))
                contag_map[i, j] = max(0, min(1, contag))
            else:
                contag_map[i, j] = 1 if p_same == 1 else 0

    return contag_map

