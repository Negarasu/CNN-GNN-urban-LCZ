def make_lst_like_cmap():
    colors = [
        "#2b6cb0",  # deep blue
        "#5fa8d3",  # blue-cyan
        "#9dd9d2",  # light cyan
        "#f3e79b",  # pale yellow
        "#f6c667",  # yellow-orange
        "#ee8f39",  # orange
        "#d84b2a",  # red-orange
        "#b2182b",  # deep red
    ]
    cmap = ListedColormap(colors, name="lst_like")
    return cmap

def make_bounds_from_data(values, n_classes=8):
    vmin = np.nanmin(values)
    vmax = np.nanmax(values)

    lo = np.floor(vmin / 5.0) * 5.0
    hi = np.ceil(vmax / 5.0) * 5.0

    bounds = np.linspace(lo, hi, n_classes + 1)
    return bounds

def nodes_to_full_map(node_values, valid_indices, original_shape):
    out = np.full(original_shape, np.nan, dtype=float)
    rows, cols = np.unravel_index(valid_indices, original_shape)
    out[rows, cols] = node_values
    return out

def build_prediction_rgba_map(
    pred_all,
    valid_indices,
    original_shape,
    norm,
    cmap,
    train_mask,
    test_mask,
    val_mask=None,
    train_alpha=0.5,
    test_alpha=1.0,
    val_alpha=0.35,
    include_val_as_context=True,
):
    H, W = original_shape
    rgba = np.zeros((H, W, 4), dtype=float)

    rows, cols = np.unravel_index(valid_indices, original_shape)

    train_idx = np.where(train_mask.cpu().numpy())[0]
    if len(train_idx) > 0:
        train_colors = cmap(norm(pred_all[train_idx]))
        train_colors[:, 3] = train_alpha
        rgba[rows[train_idx], cols[train_idx], :] = train_colors

    if include_val_as_context and (val_mask is not None):
        val_idx = np.where(val_mask.cpu().numpy())[0]
        if len(val_idx) > 0:
            val_colors = cmap(norm(pred_all[val_idx]))
            val_colors[:, 3] = val_alpha
            rgba[rows[val_idx], cols[val_idx], :] = val_colors

    test_idx = np.where(test_mask.cpu().numpy())[0]
    if len(test_idx) > 0:
        test_colors = cmap(norm(pred_all[test_idx]))
        test_colors[:, 3] = test_alpha
        rgba[rows[test_idx], cols[test_idx], :] = test_colors

    return rgba

