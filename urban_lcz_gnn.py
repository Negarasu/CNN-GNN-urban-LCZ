def calculate_PLAND(lcz_array, window_size, lcz_classes=range(1, 18)):
    """
    for each LCZ class, calculate the percentage of its area within the window around each pixel
    """

    PLAND_features = np.zeros((lcz_array.shape[0], lcz_array.shape[1], len(lcz_classes)))

    for i, lcz_class in enumerate(lcz_classes):
        binary_mask = (lcz_array == lcz_class).astype(float)
        PLAND_features[:, :, i] = ndimage.uniform_filter(binary_mask, size=window_size)

    return PLAND_features

def calculate_CONTAG(lcz_array, window_size):
    """
    Contagion to measure the extent to which patch types are aggregated or clumped
    probability that two adjacent pixels belong to the same class
    """
    H, W = lcz_array.shape
    CONTAG_map = np.zeros((H, W))

    half_window = window_size // 2
    m = len(np.unique(lcz_array))

    for i in range(H):
        for j in range(W):
            i_start = max(0, i - half_window)
            i_end = min(H, i + half_window + 1)
            j_start = max(0, j - half_window)
            j_end = min(W, j + half_window + 1)

            window = lcz_array[i_start:i_end, j_start:j_end]

            total_pairs = 0
            same_class_pairs = 0

            for x in range(window.shape[0]):
                for y in range(window.shape[1] - 1):
                    if window[x, y] == window[x, y + 1]:
                        same_class_pairs += 1
                    total_pairs += 1

            for x in range(window.shape[0] - 1):
                for y in range(window.shape[1]):
                    if window[x, y] == window[x + 1, y]:
                        same_class_pairs += 1
                    total_pairs += 1

            if total_pairs > 0:
                p_same = same_class_pairs / total_pairs
                CONTAG_map[i, j] = 1 + (p_same * np.log(p_same + 1e-8) +
                                      (1-p_same) * np.log(1-p_same + 1e-8)) / (2 * np.log(m))
            else:
                CONTAG_map[i, j] = 0

    return np.clip(CONTAG_map, 0, 1)

def calculate_SHDI(lcz_array, window_size):
    """
    Shannon Diversity Index, also known as the Shannon-Wiener index
    a measure of biodiversity that quantifies both the species richness (number of different species)
    and the evenness (abundance of each species) within a community.
    --> we use that to measure the richness and evenness of LCZ classes within each window for each pixel
    --> higher values indicate more diverse LCZ types
    It is calculated using the formula H = - sum p_i * ln(p_i)
    """

    def shannon_diversity(window):
        unique, counts = np.unique(window, return_counts=True)
        proportions = counts / counts.sum()
        return -np.sum(proportions * np.log(proportions + 1e-8))

    shdi_map = ndimage.generic_filter(lcz_array, shannon_diversity, size=window_size)
    return shdi_map

def calculate_SHAPE_AM(lcz_array, window_size):
    """
    area-weighted mean shape index, measure complexity of patch shapes
    a value of 1 indicates a square; larger values ​​indicate more complex and irregular shapes
    """
    from skimage import measure

    H, W = lcz_array.shape
    shape_map = np.zeros((H, W))

    half_window = window_size // 2
    for i in range(half_window, H - half_window):
        for j in range(half_window, W - half_window):
            window = lcz_array[i-half_window:i+half_window+1, j-half_window:j+half_window+1]
            total_shape_index = 0
            total_area = 0

            for lcz_class in np.unique(window):
                if lcz_class > 0:
                    binary_mask = (window == lcz_class)
                    if binary_mask.sum() > 0:
                        contours = measure.find_contours(binary_mask, 0.5)
                        for contour in contours:
                            perimeter = len(contour)
                            area = binary_mask.sum()
                            if area > 0 and perimeter > 0:
                                shape_idx = perimeter / (4 * np.sqrt(area))
                                total_shape_index += shape_idx * area
                                total_area += area

            if total_area > 0:
                shape_map[i, j] = total_shape_index / total_area

    return shape_map

