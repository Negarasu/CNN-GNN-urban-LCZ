class SimpleGAT(nn.Module):
    def __init__(self, node_in_dim, hidden_dim, heads, dropout=0.2):
        super().__init__()

        self.gat1 = GATConv(node_in_dim, hidden_dim, heads=heads, dropout=dropout)
        self.gat2 = GATConv(hidden_dim * heads, hidden_dim, heads=1, dropout=dropout, concat=False)

        self.output = nn.Linear(hidden_dim, 1)
        self.dropout = dropout

        self.attention_weights = None

    def forward(self, data, return_attention=False):
        x, edge_index = data.x, data.edge_index

        x, att1 = self.gat1(x, edge_index, return_attention_weights=True)
        x = F.elu(x)
        x = F.dropout(x, p=self.dropout, training=self.training)

        x, att2 = self.gat2(x, edge_index, return_attention_weights=True)
        x = F.elu(x)

        if return_attention:
            self.attention_weights = (att1, att2)

        out = self.output(x)
        return out.squeeze()

def train_simple_model(model, data, epochs, lr):
    """Better training function"""
    optimizer = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=1e-5)
    criterion = nn.MSELoss()

    train_losses = []
    val_losses = []

    for epoch in range(epochs):
        start = time.time()
        model.train()
        optimizer.zero_grad()

        out = model(data)
        loss = criterion(out[data.train_mask], data.y[data.train_mask].squeeze())

        loss.backward()
        optimizer.step()

        model.eval()
        with torch.no_grad():
            val_out = model(data)
            val_loss = criterion(val_out[data.val_mask], data.y[data.val_mask].squeeze())

        train_losses.append(loss.item())
        val_losses.append(val_loss.item())

        if epoch % 50 == 0:
            print(f'epoch {epoch:03d}, train loss: {loss:.4f}, val loss: {val_loss:.4f}, time cost: {time.time()-start:.4f}s')

    return train_losses, val_losses

def evaluate_model_simple(model, data, mask):
    """Proper evaluation"""
    model.eval()
    with torch.no_grad():
        predictions = model(data)[mask].cpu().numpy()
        targets = data.y[mask].cpu().numpy().squeeze()

        mse = ((predictions - targets) ** 2).mean()
        rmse = np.sqrt(mse)
        mae = np.abs(predictions - targets).mean()
        r2 = 1 - ((predictions - targets) ** 2).sum() / ((targets - targets.mean()) ** 2).sum()

        print(f"RMSE: {rmse:.4f}")
        print(f"MAE:  {mae:.4f}")
        print(f"R²:   {r2:.4f}")

        return predictions, targets

class SimpleAnalyzer:
    def __init__(self, model, data, feature_names, original_shape):
        self.model = model
        self.data = data
        self.feature_names = feature_names
        self.original_shape = original_shape

    def analyze_feature_importance(self):
        """Simple feature importance based on input layer weights"""
        if hasattr(self.model, 'node_encoder'):
            weights = self.model.node_encoder.weight.data.cpu().numpy()
        else:
            try:
                if hasattr(self.model.gat1, 'lin'):
                    weights = self.model.gat1.lin.weight.data.cpu().numpy()
                elif hasattr(self.model.gat1, 'weight'):
                    weights = self.model.gat1.weight.data.cpu().numpy()
                else:
                    print("Cannot access GAT layer weights directly")
                    return {}
            except:
                print("Failed to access model weights")
                return {}

        importance = np.mean(np.abs(weights), axis=0)

        min_len = min(len(importance), len(self.feature_names))
        return dict(zip(self.feature_names[:min_len], importance[:min_len]))

def get_feature_importance_alternative(model, data, feature_names):
    model.eval()

    with torch.no_grad():
        baseline_pred = model(data)
        baseline_loss = F.mse_loss(baseline_pred[data.val_mask], data.y[data.val_mask].squeeze()).item()

    importance_scores = {}

    for i, feature_name in enumerate(feature_names):
        if i >= data.x.size(1):
            break

        original_feature = data.x[:, i].clone()

        shuffled_indices = torch.randperm(data.x.size(0))
        data.x[:, i] = data.x[shuffled_indices, i]

        with torch.no_grad():
            shuffled_pred = model(data)
            shuffled_loss = F.mse_loss(shuffled_pred[data.val_mask], data.y[data.val_mask].squeeze()).item()

        data.x[:, i] = original_feature

        importance_scores[feature_name] = shuffled_loss - baseline_loss

    return importance_scores

