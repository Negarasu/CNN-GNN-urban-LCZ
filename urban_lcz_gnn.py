def create_enriched_graph_from_rasters(lcz_array, lst_array, landscape_metrics, k_neighbors=8):
    """Create graph with enriched node features including landscape metrics"""

    H, W = lcz_array.shape

    rows, cols = np.meshgrid(np.arange(H), np.arange(W), indexing='ij')
    coords = np.column_stack([rows.ravel(), cols.ravel()])

    lcz_flat = lcz_array.ravel()
    lst_flat = lst_array.ravel()

    valid_mask = (lcz_array > 0) & (lcz_array <= 17) & ~np.isnan(lst_array)
    valid_indices = np.where(valid_mask.ravel())[0]

    print(f"Number of valid nodes: {len(valid_indices)}")

    valid_coords = coords[valid_indices]
    valid_lcz = lcz_flat[valid_indices]
    valid_lst = lst_flat[valid_indices]

    knn = NearestNeighbors(n_neighbors=k_neighbors+1, algorithm='auto')
    knn.fit(valid_coords)
    distances, indices = knn.kneighbors(valid_coords)

    src = np.repeat(np.arange(len(valid_coords)), k_neighbors)
    dst = indices[:, 1:].reshape(-1)

    edge_index = torch.tensor([src, dst], dtype=torch.long)

    edge_distances = distances[:, 1:].reshape(-1, 1)
    lcz_similarity = 1.0 - (np.abs(valid_lcz[src] - valid_lcz[dst]) / 17.0).reshape(-1, 1)

    edge_attr = torch.tensor(
        np.concatenate([edge_distances, lcz_similarity], axis=1),
        dtype=torch.float32
    )

    node_features = []

    existing_lcz_classes = np.unique(valid_lcz)

    for idx, (i, j) in enumerate(valid_coords):
        feature_vector = [
            landscape_metrics['CONTAG'][i, j],           # Contagion index
            landscape_metrics['SHDI'][i, j],             # Shannon diversity index
            landscape_metrics['SHAPE_AM'][i, j],         # Shape index
            landscape_metrics['TECI'][i, j],             # Total edge contrast index
            landscape_metrics['AI'][i, j],               # Aggregation index
            landscape_metrics['PD'][i, j],               # Patch density
        ]

        # add PLAND features - only the node's own LCZ class gets 1, others get actual PLAND values
        current_lcz_class = int(valid_lcz[idx])
        for lcz_class in range(1, 18):
            if lcz_class in existing_lcz_classes:
                if lcz_class == current_lcz_class:
                    # for the node's own LCZ class, use one-hot encoding (1.0)
                    feature_vector.append(1.0)
                else:
                    # for other LCZ classes, use the actual PLAND value
                    feature_vector.append(landscape_metrics['PLAND'][i, j, lcz_class-1])

        node_features.append(feature_vector)

    x = torch.tensor(node_features, dtype=torch.float32)
    y = torch.tensor(valid_lst, dtype=torch.float32).reshape(-1, 1)

    return x, y, edge_index, edge_attr, valid_indices

